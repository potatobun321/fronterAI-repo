import { db, logAudit } from '../db.js';
import { getSessionUser } from '../middleware/session.js';
import { parseBody, sendJson } from '../middleware/httpHelpers.js';
import { chatWithAssistant } from '../services/aiService.js';

export async function handleAiRoutes(req, res, pathname, method) {
  // 1. Post a new message to the AI Chatbot
  if (pathname === '/api/ai/chat' && method === 'POST') {
    const currentUser = getSessionUser(req);
    if (!currentUser) {
      return sendJson(res, 401, { error: 'Authentication required to consult Frontier Oracle.' });
    }

    try {
      const body = await parseBody(req);
      const { message, threadId } = body;

      if (!message || !message.trim()) {
        return sendJson(res, 400, { error: 'Message text cannot be empty.' });
      }

      const result = await chatWithAssistant({
        userMessage: message,
        threadId,
        currentUser
      });

      logAudit(
        currentUser.handle,
        'AI_ORACLE_QUERY',
        `ai_thread_${result.threadId}`,
        `Queried Frontier Oracle in thread #${result.threadId}: "${message.trim().substring(0, 40)}..."`,
        'SUCCESS'
      );

      return sendJson(res, 200, result);
    } catch (err) {
      console.error('AI Oracle Error:', err);
      return sendJson(res, 500, { error: err.message || 'AI Oracle encountered an error.' });
    }
  }

  // 2. List user's conversation threads
  if (pathname === '/api/ai/threads' && method === 'GET') {
    const currentUser = getSessionUser(req);
    if (!currentUser) return sendJson(res, 401, { error: 'Authentication required' });

    const threads = db.prepare(`
      SELECT id, title, created_at, updated_at
      FROM ai_threads
      WHERE member_id = ?
      ORDER BY updated_at DESC
      LIMIT 20
    `).all(currentUser.id);

    return sendJson(res, 200, { threads });
  }

  // 3. Get message history for a specific thread
  if (pathname.match(/^\/api\/ai\/threads\/\d+\/messages$/) && method === 'GET') {
    const currentUser = getSessionUser(req);
    if (!currentUser) return sendJson(res, 401, { error: 'Authentication required' });

    const threadId = parseInt(pathname.split('/')[4], 10);
    const thread = db.prepare('SELECT * FROM ai_threads WHERE id = ?').get(threadId);

    if (!thread) return sendJson(res, 404, { error: 'Thread not found' });
    if (thread.member_id !== currentUser.id && !currentUser.is_host) {
      return sendJson(res, 403, { error: 'Forbidden: Access to another member\'s chat history is restricted.' });
    }

    const messages = db.prepare(`
      SELECT id, sender_role, content, created_at
      FROM ai_messages
      WHERE thread_id = ?
      ORDER BY id ASC
    `).all(threadId);

    return sendJson(res, 200, { thread, messages });
  }

  // 4. Delete a conversation thread
  if (pathname.match(/^\/api\/ai\/threads\/\d+$/) && method === 'DELETE') {
    const currentUser = getSessionUser(req);
    if (!currentUser) return sendJson(res, 401, { error: 'Authentication required' });

    const threadId = parseInt(pathname.split('/')[4], 10);
    const thread = db.prepare('SELECT * FROM ai_threads WHERE id = ?').get(threadId);

    if (!thread) return sendJson(res, 404, { error: 'Thread not found' });
    if (thread.member_id !== currentUser.id && !currentUser.is_host) {
      return sendJson(res, 403, { error: 'Forbidden' });
    }

    // Delete messages and thread
    db.prepare('DELETE FROM ai_messages WHERE thread_id = ?').run(threadId);
    db.prepare('DELETE FROM ai_threads WHERE id = ?').run(threadId);
    return sendJson(res, 200, { success: true, message: 'Thread deleted successfully' });
  }

  // 5. Delete all conversation threads for current user
  if (pathname === '/api/ai/threads' && method === 'DELETE') {
    const currentUser = getSessionUser(req);
    if (!currentUser) return sendJson(res, 401, { error: 'Authentication required' });

    db.prepare('DELETE FROM ai_messages WHERE thread_id IN (SELECT id FROM ai_threads WHERE member_id = ?)').run(currentUser.id);
    db.prepare('DELETE FROM ai_threads WHERE member_id = ?').run(currentUser.id);
    return sendJson(res, 200, { success: true, message: 'All conversation threads cleared.' });
  }

  // 6. Execute an action generated by Oracle with strict RBAC
  if (pathname === '/api/ai/execute' && method === 'POST') {
    const currentUser = getSessionUser(req);
    if (!currentUser) {
      return sendJson(res, 401, { error: 'Authentication required to execute workspace actions.' });
    }

    try {
      const body = await parseBody(req);
      const actionType = body.action;
      const payload = body.payload || body;

      if (!actionType) {
        return sendJson(res, 400, { error: 'Missing action type in execution payload.' });
      }

      // --- RBAC ACTION 1: CREATE_TASK (Host Only) ---
      if (actionType === 'CREATE_TASK') {
        if (!currentUser.is_host) {
          return sendJson(res, 403, { error: 'Forbidden: Only the Team Host can create or allocate tasks.' });
        }

        const title = (payload.title || '').trim();
        if (!title) return sendJson(res, 400, { error: 'Task title is required.' });

        let assigneeId = currentUser.id;
        if (payload.assigned_to) {
          const rawAssignee = String(payload.assigned_to).replace(/^@/, '').toLowerCase().trim();
          const target = db.prepare('SELECT id FROM members WHERE LOWER(handle) = ? OR LOWER(name) LIKE ? LIMIT 1')
            .get(rawAssignee, `%${rawAssignee}%`);
          if (target) assigneeId = target.id;
        }

        const track = ['frontend', 'backend', 'lead'].includes(payload.track) ? payload.track : 'backend';
        const deadline = payload.deadline || new Date(Date.now() + 7 * 86400000).toISOString().split('T')[0];
        const description = payload.description || 'Created via Frontier Oracle chat';

        const result = db.prepare(`
          INSERT INTO tasks (title, description, track, assignee_id, status, deadline, deliverable_url, version, updated_at)
          VALUES (?, ?, ?, ?, 'TODO', ?, NULL, 1, datetime('now'))
        `).run(title, description, track, assigneeId, deadline);

        logAudit(currentUser.handle, 'AI_ACTION_CREATE_TASK', `task_${result.lastInsertRowid}`, `Created task "${title}" for assignee #${assigneeId}`, 'SUCCESS');

        return sendJson(res, 200, {
          success: true,
          action: 'CREATE_TASK',
          message: `Task #${result.lastInsertRowid} ("${title}") created successfully.`,
          taskId: result.lastInsertRowid
        });
      }

      // --- RBAC ACTION 2: DELETE_TASK (Host Only) ---
      if (actionType === 'DELETE_TASK') {
        if (!currentUser.is_host) {
          return sendJson(res, 403, { error: 'Forbidden: Only the Team Host can delete tasks.' });
        }

        const taskId = parseInt(payload.task_id, 10);
        if (!taskId) return sendJson(res, 400, { error: 'Task ID is required for deletion.' });

        const task = db.prepare('SELECT id, title FROM tasks WHERE id = ?').get(taskId);
        if (!task) return sendJson(res, 404, { error: `Task #${taskId} not found.` });

        db.prepare('DELETE FROM tasks WHERE id = ?').run(taskId);
        logAudit(currentUser.handle, 'AI_ACTION_DELETE_TASK', `task_${taskId}`, `Deleted task "${task.title}"`, 'SUCCESS');

        return sendJson(res, 200, {
          success: true,
          action: 'DELETE_TASK',
          message: `Task #${taskId} deleted successfully.`
        });
      }

      // --- RBAC ACTION 3: UPDATE_TASK_STATUS (Host or Assigned Member) ---
      if (actionType === 'UPDATE_TASK_STATUS') {
        const taskId = parseInt(payload.task_id, 10);
        if (!taskId) return sendJson(res, 400, { error: 'Task ID is required.' });

        const task = db.prepare('SELECT id, title, assignee_id, status FROM tasks WHERE id = ?').get(taskId);
        if (!task) return sendJson(res, 404, { error: `Task #${taskId} not found.` });

        if (!currentUser.is_host && task.assignee_id !== currentUser.id) {
          return sendJson(res, 403, { error: 'Forbidden: You can only update tasks assigned directly to you.' });
        }

        const allowedStatuses = ['TODO', 'IN_PROGRESS', 'REVIEW', 'COMPLETED'];
        const newStatus = (payload.status || '').toUpperCase();
        if (!allowedStatuses.includes(newStatus)) {
          return sendJson(res, 400, { error: `Invalid status. Must be one of: ${allowedStatuses.join(', ')}` });
        }

        const deliverableUrl = payload.deliverable_url || null;

        db.prepare(`
          UPDATE tasks
          SET status = ?,
              deliverable_url = COALESCE(?, deliverable_url),
              version = version + 1,
              updated_at = datetime('now')
          WHERE id = ?
        `).run(newStatus, deliverableUrl, taskId);

        logAudit(currentUser.handle, 'AI_ACTION_UPDATE_TASK', `task_${taskId}`, `Updated status of task #${taskId} to ${newStatus}`, 'SUCCESS');

        return sendJson(res, 200, {
          success: true,
          action: 'UPDATE_TASK_STATUS',
          message: `Task #${taskId} status updated to ${newStatus}.`,
          task: { id: taskId, status: newStatus }
        });
      }

      // --- RBAC ACTION 4: SCHEDULE_MEETING (Host Only) ---
      if (actionType === 'SCHEDULE_MEETING') {
        if (!currentUser.is_host) {
          return sendJson(res, 403, { error: 'Forbidden: Only the Team Host can schedule workspace meetings.' });
        }

        const title = (payload.title || 'Sprint Alignment Sync').trim();
        const eventDate = payload.event_date || new Date(Date.now() + 86400000).toISOString().split('T')[0];
        const timeLabel = payload.time_label || '14:00 UTC';
        const targetAudience = payload.target_audience || 'all';
        const eventType = payload.event_type || 'SYNC';

        const result = db.prepare(`
          INSERT INTO calendar_events (title, description, event_type, event_date, time_label, target_audience, created_by)
          VALUES (?, ?, ?, ?, ?, ?, ?)
        `).run(title, 'Scheduled via Frontier Oracle', eventType, eventDate, timeLabel, targetAudience, currentUser.id);

        logAudit(currentUser.handle, 'AI_ACTION_SCHEDULE_MEETING', `calendar_${result.lastInsertRowid}`, `Scheduled meeting "${title}" on ${eventDate}`, 'SUCCESS');

        return sendJson(res, 200, {
          success: true,
          action: 'SCHEDULE_MEETING',
          message: `Meeting "${title}" scheduled for ${eventDate} at ${timeLabel}.`,
          eventId: result.lastInsertRowid
        });
      }

      // --- RBAC ACTION 5: SIGN_OFF_TICKET (Host Only) ---
      if (actionType === 'SIGN_OFF_TICKET') {
        if (!currentUser.is_host) {
          return sendJson(res, 403, { error: 'Forbidden: Only the Team Host can sign off governance tickets.' });
        }

        const ticketId = parseInt(payload.ticket_id, 10);
        if (!ticketId) return sendJson(res, 400, { error: 'Ticket ID is required.' });

        const ticket = db.prepare('SELECT id, title, status FROM access_tickets WHERE id = ?').get(ticketId);
        if (!ticket) return sendJson(res, 404, { error: `Ticket #${ticketId} not found.` });

        db.prepare(`
          UPDATE access_tickets
          SET status = 'APPROVED',
              approver_id = ?,
              resolved_at = datetime('now')
          WHERE id = ?
        `).run(currentUser.id, ticketId);

        logAudit(currentUser.handle, 'AI_ACTION_SIGN_OFF_TICKET', `ticket_${ticketId}`, `Signed off access ticket #${ticketId}`, 'SUCCESS');

        return sendJson(res, 200, {
          success: true,
          action: 'SIGN_OFF_TICKET',
          message: `Ticket #${ticketId} signed off successfully.`
        });
      }

      // --- RBAC ACTION 6: DENY_TICKET (Host Only) ---
      if (actionType === 'DENY_TICKET') {
        if (!currentUser.is_host) {
          return sendJson(res, 403, { error: 'Forbidden: Only the Team Host can deny governance tickets.' });
        }

        const ticketId = parseInt(payload.ticket_id, 10);
        if (!ticketId) return sendJson(res, 400, { error: 'Ticket ID is required.' });

        const ticket = db.prepare('SELECT id, title, status FROM access_tickets WHERE id = ?').get(ticketId);
        if (!ticket) return sendJson(res, 404, { error: `Ticket #${ticketId} not found.` });

        const reason = payload.reason || 'Denied via Frontier Oracle';

        db.prepare(`
          UPDATE access_tickets
          SET status = 'DENIED',
              approver_id = ?,
              resolved_at = datetime('now')
          WHERE id = ?
        `).run(currentUser.id, ticketId);

        logAudit(currentUser.handle, 'AI_ACTION_DENY_TICKET', `ticket_${ticketId}`, `Denied access ticket #${ticketId}: ${reason}`, 'SUCCESS');

        return sendJson(res, 200, {
          success: true,
          action: 'DENY_TICKET',
          message: `Ticket #${ticketId} has been denied.`
        });
      }

      // --- RBAC ACTION 7: START_VOTING (Host Only) ---
      if (actionType === 'START_VOTING') {
        if (!currentUser.is_host) {
          return sendJson(res, 403, { error: 'Forbidden: Only the Team Host can initiate voting sessions.' });
        }

        const title = (payload.title || 'Sprint Peer Performance Review').trim();
        const description = payload.description || 'Anonymous peer evaluation session';
        const totalEligible = payload.total_eligible || db.prepare('SELECT COUNT(*) as count FROM members WHERE is_allowed = 1').get()?.count || 8;

        // Close any prior active session
        db.prepare("UPDATE voting_sessions SET status = 'CLOSED', closed_at = datetime('now') WHERE status = 'ACTIVE'").run();

        const result = db.prepare(`
          INSERT INTO voting_sessions (title, description, session_type, status, total_eligible, created_by, created_at)
          VALUES (?, ?, 'PERFORMANCE', 'ACTIVE', ?, ?, datetime('now'))
        `).run(title, description, totalEligible, currentUser.id);

        const sessionId = result.lastInsertRowid;

        // Populate options with active team members
        const activeMembers = db.prepare('SELECT id, name FROM members WHERE is_allowed = 1').all();
        const insertOpt = db.prepare('INSERT INTO voting_options (session_id, candidate_member_id, label) VALUES (?, ?, ?)');
        for (const m of activeMembers) {
          insertOpt.run(sessionId, m.id, m.name);
        }

        logAudit(currentUser.handle, 'AI_ACTION_START_VOTING', `voting_session_${sessionId}`, `Host opened voting session #${sessionId}: "${title}"`, 'SUCCESS');

        return sendJson(res, 200, {
          success: true,
          action: 'START_VOTING',
          message: `Voting session #${sessionId} ("${title}") is now ACTIVE for ${totalEligible} members.`,
          sessionId
        });
      }

      // --- RBAC ACTION 8: TRANSFER_HOST (Host Only) ---
      if (actionType === 'TRANSFER_HOST') {
        if (!currentUser.is_host) {
          return sendJson(res, 403, { error: 'Forbidden: Only the Team Host can transfer admin authority.' });
        }

        const targetMemberId = parseInt(payload.target_member_id, 10);
        if (!targetMemberId) return sendJson(res, 400, { error: 'target_member_id is required.' });
        if (targetMemberId === currentUser.id) return sendJson(res, 400, { error: 'You are already the Team Host.' });

        const targetMember = db.prepare('SELECT * FROM members WHERE id = ?').get(targetMemberId);
        if (!targetMember || targetMember.is_allowed !== 1) {
          return sendJson(res, 404, { error: 'Target member not found or not approved.' });
        }

        try {
          db.exec('BEGIN');
          db.prepare("UPDATE members SET is_host = 1, role = 'Team Host & Lead', team_track = 'lead' WHERE id = ?").run(targetMemberId);
          db.prepare("UPDATE members SET is_host = 0, role = 'Software Engineer', team_track = 'backend' WHERE id = ?").run(currentUser.id);
          db.exec('COMMIT');
        } catch (txErr) {
          try { db.exec('ROLLBACK'); } catch (_) {}
          throw txErr;
        }

        logAudit(currentUser.handle, 'AI_ACTION_TRANSFER_HOST', `member_${targetMemberId}`, `Transferred host authority to ${targetMember.name}`, 'SUCCESS');

        return sendJson(res, 200, {
          success: true,
          action: 'TRANSFER_HOST',
          message: `Team Host authority transferred to ${targetMember.name}. You are now a contributor.`,
          newHostId: targetMemberId
        });
      }

      // --- ACTION 9: SEND_TASKLET (Direct Workspace Ping / Tasklet) ---
      if (actionType === 'SEND_TASKLET') {
        let receiverId = parseInt(payload.receiver_id, 10);
        if (!receiverId && payload.receiver) {
          const raw = String(payload.receiver).replace(/^@/, '').toLowerCase().trim();
          const target = db.prepare('SELECT id FROM members WHERE LOWER(handle) = ? OR LOWER(name) LIKE ? LIMIT 1')
            .get(raw, `%${raw}%`);
          if (target) receiverId = target.id;
        }

        if (!receiverId) return sendJson(res, 400, { error: 'Valid receiver member is required.' });

        const receiver = db.prepare('SELECT id, name, handle FROM members WHERE id = ?').get(receiverId);
        if (!receiver) return sendJson(res, 404, { error: 'Receiver member not found.' });

        const title = (payload.title || 'Workspace Ping').trim();
        const description = (payload.description || '').trim();

        const result = db.prepare(`
          INSERT INTO tasklets (sender_id, receiver_id, title, description, status, created_at, updated_at)
          VALUES (?, ?, ?, ?, 'PENDING', datetime('now'), datetime('now'))
        `).run(currentUser.id, receiverId, title, description);

        logAudit(currentUser.handle, 'AI_ACTION_SEND_TASKLET', `tasklet_${result.lastInsertRowid}`, `Sent tasklet to ${receiver.name} (@${receiver.handle}): "${title}"`, 'SUCCESS');

        return sendJson(res, 200, {
          success: true,
          action: 'SEND_TASKLET',
          message: `Tasklet delivered directly to ${receiver.name}'s workspace inbox.`,
          taskletId: result.lastInsertRowid
        });
      }

      // --- ACTION 10: SEND_FEEDBACK (All Members, Optional Anonymous) ---
      if (actionType === 'SEND_FEEDBACK') {
        let receiverId = parseInt(payload.receiver_id, 10);
        if (!receiverId && payload.receiver) {
          const raw = String(payload.receiver).replace(/^@/, '').toLowerCase().trim();
          const target = db.prepare('SELECT id FROM members WHERE LOWER(handle) = ? OR LOWER(name) LIKE ? LIMIT 1')
            .get(raw, `%${raw}%`);
          if (target) receiverId = target.id;
        }
        if (!receiverId) return sendJson(res, 400, { error: 'Valid receiver member is required.' });
        const receiver = db.prepare('SELECT id, name, handle FROM members WHERE id = ?').get(receiverId);
        if (!receiver) return sendJson(res, 404, { error: 'Receiver member not found.' });

        const title = (payload.title || 'Peer Feedback').trim();
        const description = (payload.description || '').trim();
        const category = (payload.category || 'KUDOS').toUpperCase();
        const isAnon = payload.is_anonymous ? 1 : 0;

        const result = db.prepare(`
          INSERT INTO tasklets (sender_id, receiver_id, title, description, status, type, category, is_anonymous, created_at, updated_at)
          VALUES (?, ?, ?, ?, 'PENDING', 'FEEDBACK', ?, ?, datetime('now'), datetime('now'))
        `).run(currentUser.id, receiverId, title, description, category, isAnon);

        logAudit(isAnon ? 'anonymous' : currentUser.handle, 'AI_ACTION_SEND_FEEDBACK', `tasklet_${result.lastInsertRowid}`, `Sent ${isAnon ? 'anonymous ' : ''}feedback to ${receiver.name}`, 'SUCCESS');
        return sendJson(res, 200, {
          success: true,
          action: 'SEND_FEEDBACK',
          message: `${isAnon ? 'Anonymous feedback' : 'Feedback'} delivered to ${receiver.name}.`,
          taskletId: result.lastInsertRowid
        });
      }

      // --- ACTION 11: CLOSE_VOTING (Host Only) ---
      if (actionType === 'CLOSE_VOTING') {
        if (!currentUser.is_host) {
          return sendJson(res, 403, { error: 'Forbidden: Only the Team Host can close voting sessions.' });
        }
        const active = payload.session_id
          ? db.prepare('SELECT id, title FROM voting_sessions WHERE id = ?').get(parseInt(payload.session_id, 10))
          : db.prepare("SELECT id, title FROM voting_sessions WHERE status = 'ACTIVE' ORDER BY id DESC LIMIT 1").get();
        if (!active) return sendJson(res, 404, { error: 'No active voting session found.' });

        db.prepare("UPDATE voting_sessions SET status = 'CLOSED', closed_at = datetime('now') WHERE id = ?").run(active.id);
        logAudit(currentUser.handle, 'AI_ACTION_CLOSE_VOTING', `voting_session_${active.id}`, `Closed voting session #${active.id}`, 'SUCCESS');
        return sendJson(res, 200, {
          success: true,
          action: 'CLOSE_VOTING',
          message: `Voting session #${active.id} ("${active.title}") closed and tallies revealed.`,
          sessionId: active.id
        });
      }

      // --- ACTION 12: RAISE_TICKET (All Members — 2-Man Rule) ---
      if (actionType === 'RAISE_TICKET') {
        const title = (payload.title || '').trim();
        const reason = (payload.reason || 'Requested via Frontier Oracle').trim();
        const scope = (payload.scope || 'workspace_elevated').trim();
        const duration = Math.max(5, Math.min(240, parseInt(payload.duration_minutes || 30, 10)));
        if (!title) return sendJson(res, 400, { error: 'Ticket title is required.' });

        const result = db.prepare(`
          INSERT INTO access_tickets (requester_id, title, reason, scope, duration_minutes, status, created_at)
          VALUES (?, ?, ?, ?, ?, 'PENDING_APPROVAL', datetime('now'))
        `).run(currentUser.id, title, reason, scope, duration);

        logAudit(currentUser.handle, 'AI_ACTION_RAISE_TICKET', `ticket_${result.lastInsertRowid}`, `Raised 2-Man ticket "${title}" for scope "${scope}"`, 'PENDING');
        return sendJson(res, 200, {
          success: true,
          action: 'RAISE_TICKET',
          message: `Access ticket #${result.lastInsertRowid} ("${title}") raised for peer sign-off.`,
          ticketId: result.lastInsertRowid
        });
      }

      // --- ACTION 13: PING_MEETING (Host Only) ---
      if (actionType === 'PING_MEETING') {
        if (!currentUser.is_host) {
          return sendJson(res, 403, { error: 'Forbidden: Only the Team Host can broadcast live meeting pings.' });
        }
        const ev = payload.event_id
          ? db.prepare('SELECT id, title FROM calendar_events WHERE id = ?').get(parseInt(payload.event_id, 10))
          : db.prepare("SELECT id, title FROM calendar_events WHERE event_type IN ('MEETING', 'RETRO') ORDER BY id DESC LIMIT 1").get();
        if (!ev) return sendJson(res, 404, { error: 'No meeting event found to ping.' });

        db.prepare('UPDATE calendar_events SET is_live = 1 WHERE id = ?').run(ev.id);
        logAudit(currentUser.handle, 'AI_ACTION_PING_MEETING', `cal_${ev.id}`, `Broadcasted live ping for "${ev.title}"`, 'SUCCESS');
        return sendJson(res, 200, {
          success: true,
          action: 'PING_MEETING',
          message: `Live meeting ping broadcasted for "${ev.title}".`,
          eventId: ev.id
        });
      }

      return sendJson(res, 400, { error: `Unrecognized action type: ${actionType}` });
    } catch (err) {
      console.error('Error executing Oracle action:', err);
      return sendJson(res, 500, { error: err.message || 'Failed to execute action.' });
    }
  }

  return false;
}
